"""Dimension table for DIN 472, retaining rings for bores (regular series).

Ring and groove dimensions in mm, loads in kN, weight in g per ring
(the standard lists kg per 1000 pieces, which is the same number).

Taken from the DIN 472 table distributed with bd_warehouse (Apache 2.0) and
cross-checked row by row against three independent tables:

* fasten.it's DIN 472 page (all 88 rows, d1 = 8 to 300; s, d3, a, b, d5,
  d2, m, n and weight),
* Westfield Fasteners' DIN 472 product specification (d1 = 8 to 100),
* Maedler's DIN 472 datasheet K43_N79 (41 sizes from 8 to 110).

Three errors in the source CSV were corrected; each correction is backed by
at least two of the three tables:

* d1 = 72: d3 = 76.5, not 76.6 (fasten.it, Westfield, Maedler).
* d1 = 82: s = 2.5, not 3 (fasten.it, Westfield); this also matches the
  groove width m = 2.65 used for s = 2.5 everywhere else.
* d1 = 90: d3 = 95.5, not 95.55 (fasten.it, Westfield, Maedler).

Remaining single-source disagreements, resolved in favour of the CSV:

* d1 = 78, a: fasten.it 7.9, CSV and Westfield 8.5.
* d1 = 105 and 145, d2: fasten.it 108 and 143; the CSV's 109 and 149 follow
  t = (d2 - d1) / 2 = 2 like their neighbours.
* d1 = 31 and 32, s: Westfield 1.5; the CSV, fasten.it and Maedler have 1.2,
  which matches m = 1.3.
* Isolated a, b and weight values in Maedler (d1 = 8, 10, 14, 19, 20, 24,
  90, 100) and the d1 = 19 weight in Westfield, each outvoted by the others.

Not cross-checked: d4, FN and FR come from the CSV only (d4 = 60.1 at
d1 = 78 matches Kramp's and Lemu's catalogue entries). d4 is used only to
check that the installed model stays clear of it; t is (d2 - d1) / 2 and
n is 3 t rounded up to 0.1 mm on every row (tested).
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class RingData:
    d1: float    # bore diameter (nominal size)
    s: float     # ring thickness
    d3: float    # outer diameter, free state
    a_max: float # lug height
    b: float     # radial width opposite the opening (approx.)
    d5_min: float  # plier hole diameter
    d2: float    # groove diameter
    m: float     # groove width (H13)
    t: float     # groove depth, (d2 - d1) / 2
    n_min: float # edge distance from groove to bore end
    d4: float    # clearance diameter when installed
    FN: float    # groove load capacity, kN
    FR: float    # ring load capacity, kN
    weight: float  # g per ring

    @property
    def size(self) -> str:
        return f"{self.d1:g}"


def _row(d1, s, d3, a, b, d5, d2, m, t, n, d4, FN, FR, W):
    return RingData(d1, s, d3, a, b, d5, d2, m, t, n, d4, FN, FR, W)


