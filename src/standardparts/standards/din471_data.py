"""Dimension table for DIN 471, retaining rings for shafts (regular series).

Ring and groove dimensions in mm, loads in kN, weight in g per ring
(the standard lists kg per 1000 pieces, which is the same number).

Taken from the DIN 471 table distributed with bd_warehouse (Apache 2.0) and
cross-checked against fasten.it's DIN 471 table for d1 = 3, 8, 10, 17, 25,
36, 48, 65, 100, 150, 200, 260 and 300. The two agree except n at d1 = 150
(fasten.it 6, here 7.5); 7.5 follows the n = 3 t pattern of the rest of the
table. The source CSV gives s = 2 for d1 = 48; DIN 471 (and fasten.it) has
1.75, which also matches the groove width m = 1.85 used for s = 1.75.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class RingData:
    d1: float    # shaft diameter (nominal size)
    s: float     # ring thickness
    d3: float    # inner diameter, free state
    a_max: float # lug height
    b: float     # radial width opposite the opening (approx.)
    d5_min: float  # plier hole diameter
    d2: float    # groove diameter
    m: float     # groove width (H13)
    t: float     # groove depth, (d1 - d2) / 2
    n_min: float # edge distance from groove to shaft end
    d4: float    # clearance diameter when installed
    FN: float    # groove load capacity, kN
    FR: float    # ring load capacity, kN
    weight: float  # g per ring

    @property
    def size(self) -> str:
        return f"{self.d1:g}"


def _row(d1, s, d3, a, b, d5, d2, m, t, n, d4, FN, FR, W):
    return RingData(d1, s, d3, a, b, d5, d2, m, t, n, d4, FN, FR, W)


