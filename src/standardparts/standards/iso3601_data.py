"""Size tables for ISO 3601-1:2012 (+ Amd 1:2019), O-rings: inside
diameters d1, cross-sections d2, tolerances and designation (size) codes.

The standard has two families:

* Tables 1 to 6, general industrial applications: the inch-based sizes
  d2 = 1.02 / 1.27 / 1.52 (Table 1), 1.78, 2.62, 3.53, 5.33, 6.99 (Tables
  2 to 6). Their size codes 001 to 475 are the SAE AS568 dash numbers,
  and the dimensions are the AS568 ones converted to mm. Two inside
  diameter tolerance classes: A (tight, the AS568 tolerances) and B
  (general purpose, Equation (A.1)).
* Tables 7 to 11, aerospace applications: the metric series d2 = 1.8,
  2.65, 3.55, 5.3 and 7 mm, with size codes of a cross-section letter
  A to E and four digits for d1 in tenths of a millimetre (e.g. C0630 =
  63 x 3.55). One tolerance per size. These are the "ISO 3601 metric"
  O-rings most European catalogues list. (In ISO 3601-1:2002 the metric
  sizes were the general series G and aerospace series A; the 2002 G
  table has different d1 ranges per cross-section and is not used here.)

Sources:

* ISO 3601-1:2012: clauses 6 and 7 (classes, designation codes and
  examples "O-ring-ISO3601-1-011A-7,65x1,78-S",
  "O-ring-ISO3601-1A-C0545-54,5x3,55-S"), Table 1, Table 2 complete and
  Table 3 up to code 134, both classes. ISO 3601-1:2012/Amd 1:2019:
  Table A.1, cross-section tolerances for non-standard O-rings.
* Inch-based rows (codes 001 to 475, d1 and class A tolerance): Apple
  Rubber "ISO 3601 Metric Size O-Rings" quick reference chart, cross-
  checked row by row against Prepol "ISO 3601 O-ring sizes" (2024) and,
  for codes 001 to 134, against ISO 3601-1:2012. They agree except code
  449, where Prepol has 253.57 mm / 9.983 in: AS568-449 is 9.975 in =
  253.37 mm, as Apple and the 25.4 mm conversion give.
* Class B inside diameter tolerance: Equation (A.1) of the standard,
  +/-(0.009 d1^0.95 + 0.11) rounded to 0.01 mm (third decimal 5 to 9
  rounds up). It reproduces every class B value in ISO 3601-1:2012
  Tables 1 and 2 and Table 3 up to code 134; a test checks them.
* Metric rows (codes A to E, d1): Prepol (2024) cross-checked against the
  Global O-Ring "ISO 3601 metric O-rings" chart. The d1 lists agree for
  A, B, C, D and for E up to 400 mm. Global O-Ring also lists E4120 to
  E6700 (412 to 670 mm), which Prepol does not; those 18 sizes are from
  one source only (UNVERIFIED_CODES). Both sources have typos in some
  codes (O for 0, l for 1, A0250 for 12.5, A0380 for 38.7, A0024 for
  2.24); the codes here follow the rule both sources otherwise use
  (letter + d1 x 10, rounded half up) and a test checks it.
* Metric d1 tolerances: Prepol only (single secondary source). They match
  the ISO 3601-1:2002 series A formula +/-(0.007 d1^0.96 + 0.09) with a
  0.13 mm floor to within 0.01 mm. The tolerance depends on d1 only, and
  Prepol agrees with itself across the five series except A0300 (0.26,
  while B0300 and C0300 are 0.27, as is the formula); corrected to 0.27.
  For E4120 to E6700 the tolerance is that formula (derived, not
  tabulated).
* Cross-section tolerances: class A per the table titles (2.62 is +/-0.08
  for class A, +/-0.09 for class B); otherwise Table A.1 (Amd 1:2019).
  Metric: 1.8 +/-0.08, 2.65 +/-0.09, 3.55 +/-0.10, 5.3 +/-0.13, 7 +/-0.15
  (Prepol and the 2002 edition agree).

ISO 3601-2 (housing / groove dimensions) is not included: no public
source with its tables was found.

All values are in millimetres.
"""

from __future__ import annotations

import decimal
from dataclasses import dataclass


def round_iso(x: float) -> float:
    """Round to 0.01 mm, 5 to 9 in the third decimal rounding up."""
    q = decimal.Decimal(repr(x)).quantize(decimal.Decimal("0.01"), rounding=decimal.ROUND_HALF_UP)
    return float(q)


def class_b_tolerance(d1: float) -> float:
    """Inside diameter tolerance (+/-) of class B, Equation (A.1)."""
    return round_iso(0.009 * d1 ** 0.95 + 0.11)


def metric_code(letter: str, d1: float) -> str:
    """Size code of the metric (aerospace) tables: letter + d1 in 0.1 mm."""
    n = decimal.Decimal(repr(d1 * 10)).quantize(decimal.Decimal("1"), rounding=decimal.ROUND_HALF_UP)
    return f"{letter}{int(n):04d}"


